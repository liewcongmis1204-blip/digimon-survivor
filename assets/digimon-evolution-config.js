(function attachDigimonFramework(config) {
  const STAGE_RANK = { egg: 0, in1: 1, in2: 2, rookie: 3, adult: 4, perfect: 5, ultimate: 6 };
  for (const [versionId, version] of Object.entries(config)) {
    version.versionId = versionId;
    for (const digimon of version.digimonList) {
      digimon.versionId = versionId;
      digimon.versionName = version.name;
      digimon.stageRank = STAGE_RANK[digimon.stage] ?? 0;
      // A unique, editable six-slot skill pool is attached to every species.
      if (!Array.isArray(digimon.skillPool)) {
        digimon.skillPool = Array.from({ length: 6 }, (_, index) => ({
          id: digimon.id + "_skill_" + (index + 1),
          slot: index + 1,
          name: "",
          description: "",
          tags: [],
          enabled: false
        }));
      }
      // Recipe names and ingredient IDs are intentionally blank for the user to fill later.
      if (!digimon.ultimateRecipe) {
        digimon.ultimateRecipe = {
          id: digimon.id + "_ultimate_combo",
          name: "",
          requiredSkillIds: [],
          enabled: false,
          minStage: digimon.stage,
          sealOnDevolution: true
        };
      }
      // Each outgoing branch receives its own editable skill/ultimate combo condition.
      if (!digimon.branchConditions) {
        digimon.branchConditions = Object.fromEntries((digimon.branches || []).map(targetId => [targetId, {
          enabled: true,
          requiredSkillIds: [],
          anySkillIds: [],
          requiredUltimateRecipeIds: [],
          excludedSkillIds: [],
          minLearnedSkills: 0,
          priority: 0
        }]));
      }
    }
  }
})(window.DIGIMON_EVOLUTION_CONFIG);


/*
 * 方便后续逐只填技能名称的覆盖区。
 * 不需要复制96只的完整配置；只填写需要定制的物种即可。
 * 覆盖区示例：
 * window.DIGIMON_SKILL_OVERRIDES = {
 *   "tanemon": {
 *     "skillPool": {
 *       "1": {"id":"tanemon_leaf_cut","name":"叶刃","description":"植物属性攻击","tags":["plant"],"enabled":true},
 *       "2": {"id":"tanemon_root_bind","name":"根缚","description":"控制目标","tags":["control"],"enabled":true}
 *     },
 *     "ultimateRecipe": {
 *       "id":"tanemon_ultimate_combo",
 *       "name":"森林终极连携",
 *       "requiredSkillIds":["tanemon_leaf_cut","tanemon_root_bind"],
 *       "enabled":true,
 *       "minStage":"rookie",
 *       "sealOnDevolution":true
 *     },
 *     "branchConditions": {
 *       "kabuterimon": {"requiredSkillIds":["tanemon_leaf_cut"],"priority":10},
 *       "togemon": {"requiredSkillIds":["tanemon_root_bind"],"priority":10}
 *     }
 *   }
 * };
 */
window.DIGIMON_SKILL_OVERRIDES = window.DIGIMON_SKILL_OVERRIDES || {};
(function applyDigimonSkillOverrides(config, overrides) {
  const byId = new Map();
  for (const version of Object.values(config)) for (const d of (version.digimonList || [])) byId.set(d.id, d);
  for (const [id, patch] of Object.entries(overrides || {})) {
    const d = byId.get(id);
    if (!d) { console.warn('[EvolutionConfig] 技能覆盖目标不存在：', id); continue; }
    for (const [slotNo, slotPatch] of Object.entries(patch.skillPool || {})) {
      const slot = (d.skillPool || []).find(s => String(s.slot) === String(slotNo));
      if (slot) Object.assign(slot, slotPatch, { slot: slot.slot });
    }
    if (patch.ultimateRecipe) d.ultimateRecipe = { ...(d.ultimateRecipe || {}), ...patch.ultimateRecipe };
    for (const [toId, rulePatch] of Object.entries(patch.branchConditions || {})) {
      d.branchConditions = d.branchConditions || {};
      d.branchConditions[toId] = { ...(d.branchConditions[toId] || {}), ...rulePatch };
    }
  }
})(window.DIGIMON_EVOLUTION_CONFIG, window.DIGIMON_SKILL_OVERRIDES);
